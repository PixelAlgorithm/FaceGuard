#!/usr/bin/env node
// Makes the kiosk fully offline-capable (SC2): copies the MediaPipe Tasks Vision WASM runtime from
// node_modules into public/mediapipe/wasm/ and ensures public/models/face_landmarker.task exists and
// matches the pinned SHA-256. The model is downloaded only when missing (needs internet once).
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const kioskDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const wasmSrc = path.join(kioskDir, 'node_modules/@mediapipe/tasks-vision/wasm')
const wasmDst = path.join(kioskDir, 'public/mediapipe/wasm')
const modelDst = path.join(kioskDir, 'public/models/face_landmarker.task')

// Pinned: MediaPipe face_landmarker float16 v1 (Apache-2.0).
const MODEL_URL =
  'https://storage.googleapis.com/mediapipe-models/face_landmarker/face_landmarker/float16/1/face_landmarker.task'
const MODEL_SHA256 = '64184e229b263107bc2b804c6625db1341ff2bb731874b0bcc2fe6544e0bc9ff'

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')

// Demo identities for the /register and /admin pick lists: user_id + display + role ONLY (no card hashes,
// codes or other bundle fields) from the live demo bundle source, else the test fixture.
const scheduleSources = ['../config/schedule.demo.json', '../config/schedule.example.json']
const demoUsersDst = path.join(kioskDir, 'src/shared/demoUsers.generated.ts')

function writeDemoUsers() {
  for (const rel of scheduleSources) {
    const src = path.join(kioskDir, rel)
    if (!existsSync(src)) continue
    const doc = JSON.parse(readFileSync(src, 'utf8'))
    const users = Object.entries(doc.users ?? {})
      .filter(([uid]) => /^u_[0-9a-z]{4}$/.test(uid))
      .map(([uid, u]) => ({ user_id: uid, display: String(u?.display ?? uid), role: String(u?.role ?? 'student') }))
      .sort((a, b) => a.user_id.localeCompare(b.user_id))
    const body =
      `// GENERATED by scripts/fetch-assets.mjs from ${rel.replace('../', '')} (npm run assets). Do not edit.\n` +
      `export const DEMO_USERS_SOURCE = ${JSON.stringify(rel.replace('../', ''))}\n` +
      `export const GENERATED_DEMO_USERS: Array<{ user_id: string; display: string; role: string }> = ${JSON.stringify(users, null, 2)}\n`
    const prev = existsSync(demoUsersDst) ? readFileSync(demoUsersDst, 'utf8') : ''
    if (prev !== body) writeFileSync(demoUsersDst, body)
    console.log(`[assets] demo users (${users.length}) from ${rel} -> ${path.relative(kioskDir, demoUsersDst)}`)
    return
  }
  console.warn('[assets] no schedule json found; demo user list left unchanged')
}

function copyWasm() {
  if (!existsSync(wasmSrc)) {
    throw new Error(`MediaPipe wasm not found at ${wasmSrc} - run "npm install" first`)
  }
  mkdirSync(wasmDst, { recursive: true })
  // FilesetResolver.forVisionTasks(basePath) (useModule=false) loads exactly these two files.
  // Copy only when missing or different: an identical rewrite of public/ can reload a running dev page.
  let copied = 0
  for (const f of ['vision_wasm_internal.js', 'vision_wasm_internal.wasm']) {
    const src = path.join(wasmSrc, f)
    const dst = path.join(wasmDst, f)
    if (existsSync(dst) && sha256(readFileSync(dst)) === sha256(readFileSync(src))) continue
    copyFileSync(src, dst)
    copied += 1
  }
  console.log(`[assets] mediapipe wasm -> ${path.relative(kioskDir, wasmDst)} (${copied ? `${copied} file(s) updated` : 'up to date'})`)
}

async function ensureModel() {
  if (existsSync(modelDst)) {
    const got = sha256(readFileSync(modelDst))
    if (got !== MODEL_SHA256) {
      throw new Error(`[assets] ${modelDst} sha256 mismatch: ${got} (expected ${MODEL_SHA256}). Delete it to re-download.`)
    }
    console.log('[assets] face_landmarker.task present, sha256 OK')
    return
  }
  console.log(`[assets] downloading ${MODEL_URL}`)
  const res = await fetch(MODEL_URL)
  if (!res.ok) throw new Error(`[assets] model download failed: HTTP ${res.status}`)
  const buf = Buffer.from(await res.arrayBuffer())
  const got = sha256(buf)
  if (got !== MODEL_SHA256) throw new Error(`[assets] downloaded model sha256 mismatch: ${got}`)
  mkdirSync(path.dirname(modelDst), { recursive: true })
  writeFileSync(modelDst, buf)
  console.log(`[assets] face_landmarker.task saved (${buf.length} bytes, sha256 OK)`)
}

try {
  writeDemoUsers()
  copyWasm()
  await ensureModel()
} catch (err) {
  console.error(String(err instanceof Error ? err.message : err))
  process.exit(1)
}
